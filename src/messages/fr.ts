// Tous les textes de l'interface. Une autre langue = un autre fichier de même forme.
// 135 → « 2 h 15 », 45 → « 45 min ».
function formatHours(minutes: number) {
  const rounded = Math.round(minutes);
  if (rounded < 60) return `${rounded} min`;
  const rest = rounded % 60;
  return rest ? `${Math.floor(rounded / 60)} h ${String(rest).padStart(2, "0")}` : `${rounded / 60} h`;
}

